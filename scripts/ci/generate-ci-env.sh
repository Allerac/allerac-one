#!/usr/bin/env bash
#
# Allerac One - write a throwaway env file for CI / local integration tests.
#
#   bash scripts/ci/generate-ci-env.sh                 # .env for the default Unit (CI runner)
#   bash scripts/ci/generate-ci-env.sh .env.ci-sec ci-sec   # a separate Unit on a dev host
#
# Every secret is random and generated here; no real token is ever written.
# Refuses to overwrite an existing file. For a Unit other than "allerac" it
# also moves every host port away from the defaults, so it can run next to an
# existing install (use the printed APP_PORT).

set -euo pipefail

FILE="${1:-.env}"
UNIT="${2:-allerac}"

[[ "$UNIT" =~ ^[a-z0-9][a-z0-9_-]*$ ]] || { echo "Invalid Unit name: $UNIT" >&2; exit 2; }
[ ! -e "$FILE" ] || { echo "Refusing to overwrite existing $FILE" >&2; exit 2; }

rand_hex() {
    if command -v openssl >/dev/null; then openssl rand -hex 32
    else od -An -tx1 -N32 /dev/urandom | tr -d ' \n'; fi
}

SELF_LINE=""
[ "$FILE" = ".env" ] || SELF_LINE="ALLERAC_ENV_FILE=$FILE"

umask 077
{
    echo "# Generated by scripts/ci/generate-ci-env.sh for automated tests. Throwaway values."
    [ "$UNIT" = "allerac" ] || echo "ALLERAC_UNIT=$UNIT"
    # The app loads this file via env_file; it must name itself unless it is .env.
    [ -z "$SELF_LINE" ] || echo "$SELF_LINE"
    echo "ENCRYPTION_KEY=$(rand_hex)"
    echo "TELEGRAM_TOKEN_ENCRYPTION_KEY=$(rand_hex)"
    echo "EXECUTOR_SECRET=$(rand_hex)"
    echo "POSTGRES_PASSWORD=$(rand_hex)"
    echo "ALLOW_REGISTRATION=false"
    echo "SHELL_ALLOWED_USER_IDS="
    echo "COMPOSE_PROFILES="
    # No Ollama in CI: point at a closed port so nothing waits on it.
    echo "OLLAMA_BASE_URL=http://127.0.0.1:9"
    echo "OLLAMA_MODELS="
    if [ "$UNIT" != "allerac" ]; then
        echo "APP_PORT=18180"
        echo "APP_URL=http://127.0.0.1:18180"
        echo "NEXT_PUBLIC_API_URL=http://127.0.0.1:18180"
        echo "OLLAMA_PORT=21534"
        echo "EXECUTOR_DEV_PORT=13000"
        echo "EXECUTOR_DEV_PORT_RANGE=13002-13010"
        echo "NODE_EXPORTER_PORT=19100"
        echo "PROMETHEUS_PORT=19090"
        echo "LOKI_PORT=13100"
        echo "PORTAINER_PORT=19000"
        echo "DOCS_PORT=18000"
        echo "N8N_PORT=15678"
        echo "WEBHOOK_PORT=19999"
        echo "GARMIN_WORKER_PORT=18787"
        echo "CADDY_HTTP_PORT=18880"
        echo "CADDY_HTTPS_PORT=18443"
    fi
} > "$FILE"
echo "Wrote $FILE (Unit: $UNIT)"
