#!/usr/bin/env node
// Allerac One - "no new errors" gate for tsc and ESLint.
//
// The repository still has pre-existing TypeScript and ESLint problems. This
// script compares the current problems with the committed baselines and
// fails only when something NEW appears, so CI can be required on every PR
// without fixing everything first.
//
//   node scripts/ci/check-baseline.mjs tsc        # check TypeScript
//   node scripts/ci/check-baseline.mjs eslint     # check ESLint
//   node scripts/ci/check-baseline.mjs all        # both
//   node scripts/ci/check-baseline.mjs all --update   # rewrite the baselines
//
// Baselines (committed):
//   ci/tsc-baseline.txt     one line per error:  <file>: <TScode>: <message>
//                           (no line/column, so unrelated edits that move code
//                           around do not break the gate)
//   ci/eslint-baseline.txt  one line per file/rule/severity with a count:
//                           <file>\t<rule>\t<error|warning>\t<count>
//
// A problem is "new" when its key is not in the baseline, or when the current
// count for that key is higher than the baseline count. When problems are
// fixed the check still passes and prints the command to tighten the baseline;
// please run it and commit the smaller baseline in the same PR.
//
// Options:
//   --update           write the current problems as the new baseline
//   --input <file>     read tool output from a file instead of running the tool
//                      (tsc: `tsc --noEmit --pretty false` text; eslint: `-f json`)

import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const BASELINES = {
  tsc: path.join(ROOT, 'ci/tsc-baseline.txt'),
  eslint: path.join(ROOT, 'ci/eslint-baseline.txt'),
};
const UPDATE_CMD = 'npm run baseline:update   (= node scripts/ci/check-baseline.mjs all --update)';

const args = process.argv.slice(2);
const mode = args[0];
const update = args.includes('--update');
const inputIdx = args.indexOf('--input');
const inputFile = inputIdx >= 0 ? args[inputIdx + 1] : null;
const inGitHub = process.env.GITHUB_ACTIONS === 'true';

if (!['tsc', 'eslint', 'all'].includes(mode)) {
  console.error('Usage: check-baseline.mjs <tsc|eslint|all> [--update] [--input <file>]');
  process.exit(2);
}
if (mode === 'all' && inputFile) {
  console.error('--input needs a single tool (tsc or eslint).');
  process.exit(2);
}

const rel = (p) => path.relative(ROOT, path.resolve(ROOT, p)).split(path.sep).join('/');

function run(cmd, cmdArgs) {
  const r = spawnSync(cmd, cmdArgs, { cwd: ROOT, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });
  if (r.error) throw r.error;
  return r;
}

// ---- tsc -------------------------------------------------------------
function collectTsc() {
  let out;
  if (inputFile) {
    out = readFileSync(inputFile, 'utf8');
  } else {
    const r = run(process.execPath, [path.join(ROOT, 'node_modules/typescript/bin/tsc'), '--noEmit', '--pretty', 'false']);
    out = `${r.stdout}${r.stderr}`;
    if (r.status !== 0 && !/error TS\d+/.test(out)) {
      console.error(out);
      throw new Error(`tsc failed without reporting type errors (exit ${r.status}).`);
    }
  }
  const counts = new Map();
  const locations = new Map();
  for (const line of out.split(/\r?\n/)) {
    const m = line.match(/^(.+?)\((\d+),(\d+)\): error (TS\d+): (.*)$/);
    if (!m) continue;
    const key = `${rel(m[1])}: ${m[4]}: ${m[5].trim()}`;
    counts.set(key, (counts.get(key) || 0) + 1);
    if (!locations.has(key)) locations.set(key, []);
    locations.get(key).push({ file: rel(m[1]), line: Number(m[2]), col: Number(m[3]) });
  }
  return { counts, locations };
}
function readTscBaseline() {
  const counts = new Map();
  for (const line of readFileSync(BASELINES.tsc, 'utf8').split('\n')) {
    if (!line || line.startsWith('#')) continue;
    counts.set(line, (counts.get(line) || 0) + 1);
  }
  return counts;
}
function writeTscBaseline(counts) {
  const lines = [];
  for (const [k, n] of [...counts].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    for (let i = 0; i < n; i++) lines.push(k);
  }
  const header = '# Pre-existing TypeScript errors (tsc --noEmit). Generated by scripts/ci/check-baseline.mjs.\n# Do not add lines by hand: fix new errors instead. Shrink with: npm run baseline:update\n';
  writeFileSync(BASELINES.tsc, header + lines.join('\n') + (lines.length ? '\n' : ''));
  return lines.length;
}

// ---- eslint ----------------------------------------------------------
function collectEslint() {
  let json;
  if (inputFile) {
    json = readFileSync(inputFile, 'utf8');
  } else {
    const r = run(process.execPath, [path.join(ROOT, 'node_modules/eslint/bin/eslint.js'), '.', '-f', 'json']);
    if (r.status === 2 || !r.stdout.trim().startsWith('[')) {
      console.error(r.stderr || r.stdout);
      throw new Error(`eslint crashed (exit ${r.status}).`);
    }
    json = r.stdout;
  }
  const counts = new Map();
  const locations = new Map();
  for (const file of JSON.parse(json)) {
    for (const msg of file.messages) {
      const sev = msg.severity === 2 ? 'error' : 'warning';
      const key = `${rel(file.filePath)}\t${msg.ruleId || '(parse)'}\t${sev}`;
      counts.set(key, (counts.get(key) || 0) + 1);
      if (!locations.has(key)) locations.set(key, []);
      locations.get(key).push({ file: rel(file.filePath), line: msg.line || 1, col: msg.column || 1, text: msg.message });
    }
  }
  return { counts, locations };
}
function readEslintBaseline() {
  const counts = new Map();
  for (const line of readFileSync(BASELINES.eslint, 'utf8').split('\n')) {
    if (!line || line.startsWith('#')) continue;
    const parts = line.split('\t');
    counts.set(parts.slice(0, 3).join('\t'), Number(parts[3]));
  }
  return counts;
}
function writeEslintBaseline(counts) {
  const lines = [...counts].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([k, n]) => `${k}\t${n}`);
  const header = '# Pre-existing ESLint problems: file<TAB>rule<TAB>severity<TAB>count. Generated by scripts/ci/check-baseline.mjs.\n# Do not raise counts by hand: fix new problems instead. Shrink with: npm run baseline:update\n';
  writeFileSync(BASELINES.eslint, header + lines.join('\n') + (lines.length ? '\n' : ''));
  return [...counts.values()].reduce((a, b) => a + b, 0);
}

// ---- compare ---------------------------------------------------------
function compare(tool, current, baseline) {
  const regressions = [];
  let fixed = 0;
  for (const [key, n] of current.counts) {
    const allowed = baseline.get(key) || 0;
    if (n > allowed) regressions.push({ key, extra: n - allowed, allowed, locations: current.locations.get(key) || [] });
  }
  for (const [key, n] of baseline) {
    const now = current.counts.get(key) || 0;
    if (now < n) fixed += n - now;
  }
  const total = [...current.counts.values()].reduce((a, b) => a + b, 0);
  const baseTotal = [...baseline.values()].reduce((a, b) => a + b, 0);

  if (regressions.length === 0) {
    console.log(`[${tool}] OK: ${total} known problem(s), baseline ${baseTotal}, no new ones.`);
    if (fixed > 0) {
      const note = `[${tool}] ${fixed} baseline problem(s) are fixed. Tighten the baseline so they cannot come back: ${UPDATE_CMD}`;
      console.log(note);
      if (inGitHub) console.log(`::notice title=${tool} baseline can shrink::${note}`);
    }
    return true;
  }

  console.log(`[${tool}] FAIL: ${regressions.reduce((a, r) => a + r.extra, 0)} new problem(s) (current ${total}, baseline ${baseTotal}).`);
  for (const r of regressions) {
    console.log(`  + ${r.key.replace(/\t/g, '  ')}   (${r.extra} more than the ${r.allowed} allowed)`);
    for (const loc of r.locations) {
      console.log(`      ${loc.file}:${loc.line}:${loc.col}${loc.text ? `  ${loc.text}` : ''}`);
      if (inGitHub) {
        const msg = (loc.text || r.key.split(': ').slice(2).join(': ')).replace(/\r?\n/g, ' ');
        console.log(`::error file=${loc.file},line=${loc.line},col=${loc.col},title=new ${tool} problem::${msg}`);
      }
    }
  }
  console.log(`[${tool}] Fix the new problem(s) above. Lines are reported per location; a key that already had`);
  console.log(`[${tool}] N known problems fails when it gets N+1, so look at the listed locations for the new one.`);
  console.log(`[${tool}] Only if a problem was deliberately accepted (rare), regenerate with: ${UPDATE_CMD}`);
  return false;
}

const tools = mode === 'all' ? ['tsc', 'eslint'] : [mode];
let ok = true;
for (const tool of tools) {
  const current = tool === 'tsc' ? collectTsc() : collectEslint();
  if (update) {
    const n = tool === 'tsc' ? writeTscBaseline(current.counts) : writeEslintBaseline(current.counts);
    console.log(`[${tool}] Baseline written: ${rel(BASELINES[tool])} (${n} problem(s)).`);
    continue;
  }
  if (!existsSync(BASELINES[tool])) {
    console.error(`[${tool}] Missing ${rel(BASELINES[tool])}. Create it with: ${UPDATE_CMD}`);
    ok = false;
    continue;
  }
  const baseline = tool === 'tsc' ? readTscBaseline() : readEslintBaseline();
  ok = compare(tool, current, baseline) && ok;
}
process.exit(ok ? 0 : 1);
